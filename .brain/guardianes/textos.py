def idioma_del_proyecto():
    """El `idioma` del guardianes.json que está junto a este archivo; español si no hay o no se puede leer."""
    try:
        with open(os.path.join(AQUI, "guardianes.json"), encoding="utf-8") as f:
            return json.load(f).get("idioma", "es")
    except Exception:
        return "es"


def idioma(cfg_o_codigo=None):
    """«es» o «en» a partir de guardianes.json (dict), de un código suelto o, con None, del guardianes.json del
    proyecto; cualquier otra cosa es español."""
    if cfg_o_codigo is None:
        cfg_o_codigo = idioma_del_proyecto()
    valor = cfg_o_codigo.get("idioma", "es") if isinstance(cfg_o_codigo, dict) else cfg_o_codigo
    valor = str(valor or "es").strip().lower()
    return "en" if valor in ("en", "english", "inglés", "ingles") or valor.startswith("en-") else "es"


def t(cfg_o_codigo, clave, *args):
    """Texto de `clave` en el idioma del proyecto, con los valores de `args` (formato %)."""
    plantilla = TEXTOS[idioma(cfg_o_codigo)].get(clave) or TEXTOS["es"][clave]
    return plantilla % args if args else plantilla


def tp(clave, *args):
    """Como t(), en el idioma del guardianes.json del proyecto (para funciones que no reciben la configuración).
    Sin `args` devuelve la plantilla tal cual, para usarla con `%` como antes."""
    return t(None, clave, *args)
